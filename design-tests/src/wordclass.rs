//! v12 — ADDRESSES THAT ABSTRACT.
//!
//! [[v11]] measured the ceiling: 98.66% on training positions, 35.5% on held-out ones.
//! The error is entirely generalisation, and every experiment that helped in this
//! project made stored knowledge easier to REACH while every experiment that added
//! machinery failed. So the lever is addressing, and the deepest problem with the
//! addressing is that every key is a literal word.
//!
//! `QW:dog` and `QW:puppy` are unrelated symbols. A reply stored under one cannot be
//! reached by the other, however similar they are, because the address is spelling.
//!
//! The fix needs a notion of similarity that is not spelling — and there is one that
//! this substrate can actually compute, because it is counting:
//!
//!     Harris (1954): words that occur in similar CONTEXTS have similar meanings.
//!
//! So: build each word's context profile by counting its neighbours, then hash that
//! profile down to a handful of class labels. Two words used the same way collide in
//! some of those labels even if they share no letters. Those labels become extra
//! identity keys, and identity keys are free (v9 §3e) — the competition returns a
//! fixed number of winners however many you supply, so a better address simply wins.
//!
//! This is learned from the data, by counting, with no gradient descent anywhere. It
//! is the cheapest honest answer to "a representation of similarity that is not
//! spelling", and whether it actually closes any of the 63-point gap is a measurement.

use std::collections::HashMap;

use crate::v6::fnv1a;

/// How many independent bands of bits. More bands = more chances for two similar
/// words to collide somewhere, which is the same graded-backoff idea as the identity
/// ladder: several addresses of decreasing specificity rather than one exact one.
pub const BANDS: usize = 4;
/// Bits per band. 5 bits = 32 buckets per band, so a band is a coarse class.
pub const BITS: usize = 5;

pub struct WordClasses {
    /// word -> one class label per band
    pub class: HashMap<String, [u8; BANDS]>,
    pub vocab: usize,
}

impl WordClasses {
    /// Count each word's neighbours, then hash the profile into class labels.
    ///
    /// `docs` yields tokenized sentences. `window` is how far each side counts as
    /// context. Words seen fewer than `min_count` times get no class — a profile
    /// built from three observations is noise, and a noisy class is worse than none.
    pub fn build<'a, I>(docs: I, window: usize, min_count: u32) -> WordClasses
    where
        I: Iterator<Item = &'a [String]>,
    {
        // ---- 1. context profiles. profile[w] maps a context word to a count.
        let mut prof: HashMap<&str, HashMap<&str, u32>> = HashMap::new();
        let mut freq: HashMap<&str, u32> = HashMap::new();
        for toks in docs {
            for (i, w) in toks.iter().enumerate() {
                *freq.entry(w.as_str()).or_insert(0) += 1;
                let lo = i.saturating_sub(window);
                let hi = (i + window + 1).min(toks.len());
                let e = prof.entry(w.as_str()).or_default();
                for (j, c) in toks[lo..hi].iter().enumerate() {
                    if lo + j != i {
                        *e.entry(c.as_str()).or_insert(0) += 1;
                    }
                }
            }
        }

        // ---- 2. project each profile onto random +-1 directions and keep the signs.
        //
        // This is a random hyperplane LSH (Charikar 2002): the probability that two
        // profiles land on the same side of a random hyperplane rises with their
        // cosine similarity, so words used the same way agree on most bits. The
        // "random" vectors are generated by hashing, so nothing has to be stored.
        let total_tokens: f32 = freq.values().map(|&x| x as f32).sum::<f32>().max(1.0);
        let mut class: HashMap<String, [u8; BANDS]> = HashMap::new();
        let total_bits = BANDS * BITS;
        for (w, ctx) in &prof {
            if freq.get(w).copied().unwrap_or(0) < min_count {
                continue;
            }
            // POINTWISE MUTUAL INFORMATION, and the first version got this wrong.
            //
            // With raw counts (even divided by sqrt(freq)) every profile is dominated
            // by the words that are common everywhere, so every profile points in
            // nearly the same direction and the projections measure "are you a word"
            // rather than "which word". Measured: band 0 used 2 of 32 buckets and one
            // held 2,455 words — `dog`, `monday` and `hospital` all in the same class.
            //
            // PMI centres it. ln( p(context | word) / p(context) ) is positive when a
            // context occurs MORE around this word than around words in general,
            // negative when less, and near zero for words that occur near everything.
            // Function words cancel instead of dominating, which is the same lesson
            // as every hub feature in this project: what is shared by everything
            // discriminates nothing.
            let n_w: f32 = ctx.values().map(|&x| x as f32).sum::<f32>().max(1.0);
            let mut bits: Vec<f32> = vec![0.0; total_bits];
            for (c, &n) in ctx {
                let cf = freq.get(c).copied().unwrap_or(1) as f32;
                let p_c_given_w = n as f32 / n_w;
                let p_c = cf / total_tokens;
                let weight = (p_c_given_w / p_c).ln();
                for b in 0..total_bits {
                    let h = fnv1a(c.as_bytes(), 0xC1A55 + b as u64);
                    // one pseudo-random +-1 per (context word, bit).
                    //
                    // NOT `h & 1`. FNV-1a's multiplier is odd, so bit 0 of the product
                    // is bit 0 of the input — the low bit never mixes, and `h & 1`
                    // reduces to parity(bytes) XOR parity(seed). With seeds `base + b`
                    // the parity alternates with b, so every even bit-plane got one
                    // sign pattern and every odd plane its exact negation: TWO real
                    // projections wearing twenty hats. Measured: band 0 used 2 of 32
                    // buckets, one holding 2,455 words, and `dog` classed with
                    // `monday`. The high bits avalanche properly.
                    let sign = if (h >> 33) & 1 == 0 { 1.0 } else { -1.0 };
                    bits[b] += sign * weight;
                }
            }
            let mut labels = [0u8; BANDS];
            for b in 0..BANDS {
                let mut v = 0u8;
                for k in 0..BITS {
                    if bits[b * BITS + k] > 0.0 {
                        v |= 1 << k;
                    }
                }
                labels[b] = v;
            }
            class.insert((*w).to_string(), labels);
        }
        let vocab = class.len();
        WordClasses { class, vocab }
    }

    /// The class keys for one word, most specific band first. Empty if the word was
    /// too rare to profile — in which case she simply falls back to the literal
    /// address, exactly as the identity ladder already does.
    pub fn keys(&self, w: &str) -> Vec<String> {
        match self.class.get(w) {
            None => Vec::new(),
            Some(l) => (0..BANDS).map(|b| format!("{}:{}", b, l[b])).collect(),
        }
    }

    /// How many distinct words share this word's first-band class — a quick read on
    /// whether the classes are carving anything up or just hashing everything apart.
    pub fn band0_sizes(&self) -> Vec<usize> {
        let mut n = vec![0usize; 1 << BITS];
        for l in self.class.values() {
            n[l[0] as usize] += 1;
        }
        n
    }
}

/// Expose the raw PMI-weighted profiles, so the QUALITY of the representation can be
/// checked directly instead of only through the hash that compresses it.
pub fn profiles<'a, I>(docs: I, window: usize, min_count: u32)
    -> (HashMap<String, HashMap<String, f32>>, HashMap<String, u32>, f32)
where I: Iterator<Item = &'a [String]>
{
    let mut cnt: HashMap<String, HashMap<String, u32>> = HashMap::new();
    let mut freq: HashMap<String, u32> = HashMap::new();
    for toks in docs {
        for (i, w) in toks.iter().enumerate() {
            *freq.entry(w.clone()).or_insert(0) += 1;
            let lo = i.saturating_sub(window);
            let hi = (i + window + 1).min(toks.len());
            let e = cnt.entry(w.clone()).or_default();
            for (j, c) in toks[lo..hi].iter().enumerate() {
                if lo + j != i { *e.entry(c.clone()).or_insert(0) += 1; }
            }
        }
    }
    let total: f32 = freq.values().map(|&x| x as f32).sum::<f32>().max(1.0);
    let mut out: HashMap<String, HashMap<String, f32>> = HashMap::new();
    for (w, ctx) in cnt {
        if freq.get(&w).copied().unwrap_or(0) < min_count { continue; }
        let n_w: f32 = ctx.values().map(|&x| x as f32).sum::<f32>().max(1.0);
        let mut v = HashMap::new();
        for (c, n) in ctx {
            let cf = freq.get(&c).copied().unwrap_or(1) as f32;
            let pmi = ((n as f32 / n_w) / (cf / total)).ln();
            if pmi > 0.0 { v.insert(c, pmi); }   // PPMI: keep the positive associations
        }
        out.insert(w, v);
    }
    (out, freq, total)
}

pub fn cosine(a: &HashMap<String, f32>, b: &HashMap<String, f32>,
              _f: &HashMap<String, u32>, _t: f32) -> f32 {
    let (mut dot, mut na, mut nb) = (0.0f32, 0.0f32, 0.0f32);
    for (k, x) in a { na += x * x; if let Some(y) = b.get(k) { dot += x * y; } }
    for y in b.values() { nb += y * y; }
    if na <= 0.0 || nb <= 0.0 { 0.0 } else { dot / (na.sqrt() * nb.sqrt()) }
}

/// The distributional neighbours of each word: its `k` nearest by cosine over PPMI
/// profiles, above `floor`.
///
/// This replaces the LSH entirely. Hashing the profiles was the wrong move and the
/// measurement said so: the profiles carry real similarity (monday -> tuesday 0.25,
/// friday 0.24, wednesday 0.20; she -> he 0.17; eat -> cook, ate, eating) but the
/// cosines top out around 0.25, and random-hyperplane LSH needs near-duplicates to
/// collide. Five bits threw the signal away — `dog` classed with `monday`.
///
/// Neighbours need no new machinery at all, which is the point. v11 measured that
/// every change which helped this project made stored knowledge easier to REACH and
/// every change that added mechanism failed. So: emit the neighbours as ADDITIONAL
/// KEYS in the format that already exists. A reply filed under "tuesday" becomes
/// reachable by "monday", because "monday" now also addresses "tuesday"'s drawer.
pub fn neighbours(
    prof: &HashMap<String, HashMap<String, f32>>, k: usize, floor: f32,
) -> HashMap<String, Vec<String>> {
    // index by context word so only profiles that actually share a context are
    // compared — the vocabulary is a few thousand words but the pairs that overlap
    // at all are far fewer, and comparing every pair is quadratic for nothing.
    let mut by_ctx: HashMap<&str, Vec<&str>> = HashMap::new();
    for (w, v) in prof {
        for c in v.keys() {
            by_ctx.entry(c.as_str()).or_default().push(w.as_str());
        }
    }
    let norm: HashMap<&str, f32> = prof.iter()
        .map(|(w, v)| (w.as_str(), v.values().map(|x| x * x).sum::<f32>().sqrt().max(1e-9)))
        .collect();

    let mut out: HashMap<String, Vec<String>> = HashMap::new();
    for (w, v) in prof {
        let mut dot: HashMap<&str, f32> = HashMap::new();
        for (c, x) in v {
            // a context shared by half the vocabulary tells us nothing and costs the
            // most time; skip it. same hub lesson, fifth appearance.
            let Some(sharers) = by_ctx.get(c.as_str()) else { continue };
            if sharers.len() > 400 { continue; }
            for o in sharers {
                if *o == w.as_str() { continue; }
                if let Some(y) = prof[*o].get(c) {
                    *dot.entry(o).or_insert(0.0) += x * y;
                }
            }
        }
        let nw = norm[w.as_str()];
        let mut best: Vec<(f32, &str)> = dot.into_iter()
            .map(|(o, d)| (d / (nw * norm[o]), o))
            .filter(|(s, _)| *s >= floor)
            .collect();
        best.sort_by(|a, b| b.0.total_cmp(&a.0));
        best.truncate(k);
        if !best.is_empty() {
            out.insert(w.clone(), best.into_iter().map(|(_, o)| o.to_string()).collect());
        }
    }
    out
}

/// v15 — CLASSES, not neighbours.
///
/// v12 used the distributional profiles to produce a NEIGHBOUR LIST and spent it as
/// extra spellings of an identity key. That bought 0.35 points, because a different
/// spelling of a key that is already too specific is still too specific.
///
/// v14 said what is actually needed. 27% of held-out positions have no address at all
/// and sit at 22.8% correct, flat across a 4x range of training data — because what
/// they have in common is a novel COMBINATION of familiar words, and data cannot teach
/// a combination it never sees. What generalises across combinations is not a longer
/// list of words, it is a smaller set of them:
///
///     `QW:hungry|R1:why` never occurred.  `C:<food-ish>|C:<question-opener>` occurred
///     thousands of times.
///
/// So collapse the vocabulary to `n` classes. The `n` most frequent profiled words are
/// the exemplars; every word joins whichever exemplar it is most similar to. That is
/// the crudest possible clustering and it is chosen on purpose — v12's lesson was that
/// random-hyperplane hashing destroyed the similarity it was given, and an exemplar
/// assignment cannot: it compares real profiles by real cosine and nothing is thrown
/// away but the identity of the winner.
pub fn exemplar_classes(
    prof: &HashMap<String, HashMap<String, f32>>,
    freq: &HashMap<String, u32>,
    n: usize,
) -> (HashMap<String, u16>, Vec<String>) {
    let mut words: Vec<&String> = prof.keys().collect();
    words.sort_unstable_by(|a, b| {
        freq.get(*b).copied().unwrap_or(0).cmp(&freq.get(*a).copied().unwrap_or(0))
            .then(a.cmp(b))
    });
    let ex: Vec<String> = words.iter().take(n).map(|w| (*w).clone()).collect();
    let dummy_f: HashMap<String, u32> = HashMap::new();
    let mut out: HashMap<String, u16> = HashMap::with_capacity(words.len());
    for w in &words {
        let pw = &prof[*w];
        let mut best = (f32::NEG_INFINITY, 0u16);
        for (i, e) in ex.iter().enumerate() {
            let s = cosine(pw, &prof[e], &dummy_f, 0.0);
            if s > best.0 { best = (s, i as u16); }
        }
        out.insert((*w).clone(), best.1);
    }
    (out, ex)
}
